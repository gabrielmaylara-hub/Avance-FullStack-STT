CREATE TABLE IF NOT EXISTS usuarios (
  id text PRIMARY KEY,
  usuario text NOT NULL UNIQUE,
  nombre text NOT NULL,
  rol text NOT NULL CHECK (rol IN ('administrador', 'tecnico')),
  password_hash text NOT NULL,
  creado timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sesiones (
  id uuid PRIMARY KEY,
  usuario_id text NOT NULL REFERENCES usuarios(id),
  expira timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS sesiones_expira_idx ON sesiones (expira);

CREATE TABLE IF NOT EXISTS intentos_login (
  clave text PRIMARY KEY,
  fallos integer NOT NULL,
  hasta timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS solicitudes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente text NOT NULL CHECK (cliente ~ '^CLI-[0-9]{3,8}$'),
  titulo text NOT NULL CHECK (length(titulo) BETWEEN 3 AND 120),
  descripcion text NOT NULL CHECK (length(descripcion) BETWEEN 10 AND 1000),
  categoria text NOT NULL CHECK (categoria IN ('Mantenimiento', 'Soporte', 'Redes')),
  prioridad text NOT NULL CHECK (prioridad IN ('Baja', 'Media', 'Alta', 'Crítica')),
  estado text NOT NULL CHECK (estado IN ('Pendiente', 'En proceso', 'Resuelta')),
  creado timestamptz NOT NULL DEFAULT now(),
  actualizado timestamptz NOT NULL DEFAULT now(),
  creado_por text NOT NULL REFERENCES usuarios(id),
  version integer NOT NULL DEFAULT 1 CHECK (version > 0)
);
CREATE INDEX IF NOT EXISTS solicitudes_estado_idx ON solicitudes (estado, id DESC);

CREATE TABLE IF NOT EXISTS actividad (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Se conserva el folio del movimiento aun después de eliminar la solicitud.
  solicitud_id integer NOT NULL,
  usuario_id text NOT NULL REFERENCES usuarios(id),
  accion text NOT NULL,
  detalle text NOT NULL,
  fecha timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS inicializacion (
  nombre text PRIMARY KEY
);
